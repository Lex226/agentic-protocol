import { execFileSync } from 'node:child_process';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { readProtocolSources } from './lib/source.mjs';
import { renderAdapters } from './lib/render.mjs';
import { inspectTargets, writeTargets } from './lib/targets.mjs';

const SHA_RE = /^[0-9a-f]{40}$/;

function usage() {
  return 'usage: generate-adapters.mjs (--write | --check) --target <dir> [--protocol-root <dir>] [--source-sha <40-hex>]';
}

function parseArgs(argv) {
  const args = {
    write: false,
    check: false,
    target: '',
    protocolRoot: '',
    sourceSha: '',
    help: false,
  };
  for (let i = 0; i < argv.length; i += 1) {
    const token = argv[i];
    if (token === '--write') args.write = true;
    else if (token === '--check') args.check = true;
    else if (token === '--help' || token === '-h') args.help = true;
    else if (token === '--target' || token === '--protocol-root' || token === '--source-sha') {
      const value = argv[i + 1];
      if (!value || value.startsWith('--')) {
        throw new Error(`missing value for ${token}`);
      }
      i += 1;
      if (token === '--target') args.target = value;
      if (token === '--protocol-root') args.protocolRoot = value;
      if (token === '--source-sha') args.sourceSha = value;
    } else {
      throw new Error(`unknown argument: ${token}`);
    }
  }
  return args;
}

function gitHead(protocolRoot) {
  return execFileSync('git', ['rev-parse', 'HEAD'], {
    cwd: protocolRoot,
    encoding: 'utf8',
    stdio: ['ignore', 'pipe', 'pipe'],
  }).trim();
}

export function runGenerate(argv, { protocolRoot: defaultRoot } = {}) {
  let args;
  try {
    args = parseArgs(argv);
  } catch (error) {
    console.error(error.message);
    console.error(usage());
    return 3;
  }
  if (args.help || args.write === args.check || !args.target) {
    console.error(usage());
    return 3;
  }

  const protocolRoot = path.resolve(
    args.protocolRoot || defaultRoot || path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..'),
  );
  const targetRoot = path.resolve(args.target);
  let sourceSha = args.sourceSha;
  if (!sourceSha) {
    try {
      sourceSha = gitHead(protocolRoot);
    } catch (error) {
      console.error('source SHA is unavailable. Pass --source-sha or run inside a protocol git checkout.');
      console.error(error.stderr?.toString?.() || error.message);
      return 3;
    }
  }
  if (!SHA_RE.test(sourceSha)) {
    console.error(`source SHA must be 40 lowercase hex characters: ${sourceSha}`);
    return 3;
  }

  let sources;
  try {
    sources = readProtocolSources(protocolRoot);
  } catch (error) {
    console.error(error.message);
    return 3;
  }

  const rendered = renderAdapters({
    protocolVersion: sources.protocolVersion,
    sourceSha,
    protocolMarkdown: sources.protocolMarkdown,
    templates: sources.templates,
  });
  const { conflicts, drifts, unsafe } = inspectTargets(targetRoot, rendered);
  if (unsafe.length > 0) {
    for (const item of unsafe) console.error(`unsafe path: ${item}`);
    console.error('no files were written');
    return 3;
  }
  if (conflicts.length > 0) {
    for (const abs of conflicts) {
      console.error(`conflict: refusing to overwrite ${abs} (not generated by agentic-protocol)`);
    }
    console.error('no files were written');
    return 2;
  }
  if (args.check) {
    if (drifts.length > 0) {
      for (const rel of drifts) console.error(`stale: ${rel}`);
      return 1;
    }
    console.log('adapters are current');
    return 0;
  }

  writeTargets(targetRoot, rendered);
  console.log('adapters written');
  return 0;
}

function isDirectRun() {
  const entry = process.argv[1];
  if (!entry) return false;
  return import.meta.url === pathToFileURL(path.resolve(entry)).href;
}

if (isDirectRun()) {
  process.exit(runGenerate(process.argv.slice(2)));
}
